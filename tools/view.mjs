#!/usr/bin/env node
// Readable view of experimentos.jsonl → docs/EXPERIMENTOS.md (one table per sequence).
// The .jsonl stays the official deliverable; this file is only for humans.
// Adds: an index of sequences, a status legend, the sequence name from experiments/<seq>-<name>.json,
// and a note on every sequence that experiments/superseded.json marks as recorded under v1.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { readJsonl } from './lib.mjs';

const lines = readJsonl('experimentos.jsonl');
const cell = (v) => String(typeof v === 'string' ? v : JSON.stringify(v)).replace(/\|/g, '\\|');
const bySeq = new Map();
for (const l of lines) (bySeq.get(l.seq) ?? bySeq.set(l.seq, []).get(l.seq)).push(l);

const superseded = existsSync('experiments/superseded.json') ? JSON.parse(readFileSync('experiments/superseded.json', 'utf8')) : {};
// experiments/s04-reglas.json → { s04: 'reglas' }
const names = {};
for (const f of readdirSync('experiments')) {
  const m = f.match(/^(s\d{2})-(.+)\.json$/);
  if (m) names[m[1]] = m[2];
}
const baseOf = (seq) => seq.replace(/-drift\d+$/, '');
const isDrift = (seq) => /-drift\d+$/.test(seq);
const reasonFor = (seq) => superseded[seq] ?? superseded[baseOf(seq)] ?? null;

const STATUS = {
  200: 'OK',
  201: 'creado (alta de cuenta)',
  400: 'error de formato o validación (E1xx–E3xx, orden de la tabla de errores)',
  401: 'sin autorización (token)',
  404: 'no encontrado (ruta, cuenta u operación)',
  409: 'bloqueo v1 (E510 con 409, sin intentos)',
  422: 'regla de negocio (E506 límite, E507 saldo)',
  423: 'bloqueo v2 (E510 con 423 y "intentos":N)',
};
const usedStatus = [...new Set(lines.map((l) => String(l.status)))].sort();

const requests = lines.length;
const seqCount = bySeq.size;
const supCount = [...bySeq.keys()].filter((s) => reasonFor(s)).length;

let md = `# Experiment log (readable view)

Generated by \`tools/view.mjs\` from \`experimentos.jsonl\` (${requests} requests, ${seqCount} sequences, ${supCount} marked as superseded). Do not edit by hand. Each sequence starts after \`POST /__reset\`; the reset itself is not logged.

## How to read it

- **Sequence**: a run of requests against the original, with one hypothesis per request. \`sNN\` is the experiment file in \`experiments/\`; \`-driftN\` is a daily re-run of that sequence by \`tools/drift.mjs\` (same requests, compared with the recorded original).
- **Superseded**: the sequence was recorded under v1 (before the v2 incident FR-0153). It stays as evidence and is not a test (see \`experiments/superseded.json\`).
- **Conclusion**: the claim that the row supports. Rows from id 555 on have template conclusions (prefix \`v2 (seq):\`) merged from \`experiments/conclusiones.json\`; read them against the status and response.
- **Status codes** in this log:

| Status | Meaning in this log |
|---|---|
${usedStatus.map((s) => `| ${s} | ${STATUS[s] ?? ''} |`).join('\n')}

## Index

| Sequence | Name (file) | Requests | State |
|---|---|---|---|
${[...bySeq].map(([seq, ls]) => {
  const base = baseOf(seq);
  const name = names[base] ? `${base} — ${names[base]}` : seq;
  const state = reasonFor(seq) ? 'superseded (v1)' : 'current';
  return `| [${seq}](#${seq.toLowerCase()}) | ${name} | ${ls.length} | ${state} |`;
}).join('\n')}
`;

for (const [seq, ls] of bySeq) {
  const base = baseOf(seq);
  const heading = names[base] && !isDrift(seq) ? `${seq} — ${names[base]}` : isDrift(seq) ? `${seq} (drift re-run of ${base}${names[base] ? ' — ' + names[base] : ''})` : seq;
  md += `\n<a id="${seq.toLowerCase()}"></a>\n\n## ${heading}\n\n`;
  const reason = reasonFor(seq);
  if (reason) md += `> **Superseded (v1):** ${reason}\n\n`;
  md += `| id | Hypothesis | Request | Status | Response | Conclusion |\n|---|---|---|---|---|---|\n`;
  for (const l of ls) {
    const req = [l.method, l.path].filter(Boolean).join(' ') + (l.auth === false ? ' (no token)' : l.token ? ' (other token)' : '');
    md += `| ${l.id} | ${cell(l.hipotesis)} | ${req ? cell(req) + ' ' : ''}\`${cell(l.request)}\` | ${l.status} | \`${cell(l.response)}\` | ${cell(l.conclusion ?? '')} |\n`;
  }
}
mkdirSync('docs', { recursive: true });
writeFileSync('docs/EXPERIMENTOS.md', md);
console.log(`docs/EXPERIMENTOS.md: ${lines.length} rows, ${seqCount} sequences`);
